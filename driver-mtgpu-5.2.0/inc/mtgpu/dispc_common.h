static inline u32 pixel_format_to_bpp(enum MT_PIXEL_FORMAT_ID format)
{
	u32 bpp = 32;

	switch (format) {
	case MT_PIXEL_FORMAT_ARGB8888:
	case MT_PIXEL_FORMAT_ARBG8888:
	case MT_PIXEL_FORMAT_ABGR8888:
	case MT_PIXEL_FORMAT_ABRG8888:
	case MT_PIXEL_FORMAT_AGRB8888:
	case MT_PIXEL_FORMAT_AGBR8888:

	case MT_PIXEL_FORMAT_RGBA8888:
	case MT_PIXEL_FORMAT_RBGA8888:
	case MT_PIXEL_FORMAT_BGRA8888:
	case MT_PIXEL_FORMAT_BRGA8888:
	case MT_PIXEL_FORMAT_GRBA8888:
	case MT_PIXEL_FORMAT_GBRA8888:

	case MT_PIXEL_FORMAT_XRGB8888:
	case MT_PIXEL_FORMAT_XBGR8888:
	case MT_PIXEL_FORMAT_RGBX8888:
	case MT_PIXEL_FORMAT_BGRX8888:

	/* A2R10G10B10(1PLANE) */
	case MT_PIXEL_FORMAT_ARGB2101010:
	case MT_PIXEL_FORMAT_ARBG2101010:
	case MT_PIXEL_FORMAT_ABGR2101010:
	case MT_PIXEL_FORMAT_ABRG2101010:
	case MT_PIXEL_FORMAT_AGRB2101010:
	case MT_PIXEL_FORMAT_AGBR2101010:

	case MT_PIXEL_FORMAT_RGBA1010102:
	case MT_PIXEL_FORMAT_RBGA1010102:
	case MT_PIXEL_FORMAT_BGRA1010102:
	case MT_PIXEL_FORMAT_BRGA1010102:
	case MT_PIXEL_FORMAT_GRBA1010102:
	case MT_PIXEL_FORMAT_GBRA1010102:

	case MT_PIXEL_FORMAT_XRGB2101010:
	case MT_PIXEL_FORMAT_XBGR2101010:
	case MT_PIXEL_FORMAT_RGBX1010102:
	case MT_PIXEL_FORMAT_BGRX1010102:
		bpp = 32;
		break;
	case MT_PIXEL_FORMAT_XRGB16161616F:
	case MT_PIXEL_FORMAT_XBGR16161616F:
	case MT_PIXEL_FORMAT_ARGB16161616F:
	case MT_PIXEL_FORMAT_ABGR16161616F:
		bpp = 64;
		break;
	case MT_PIXEL_FORMAT_YUV420_2PLANE_PACK8:
	case MT_PIXEL_FORMAT_YVU420_2PLANE_PACK8:
		bpp = 8;
		break;
	case MT_PIXEL_FORMAT_YUV420_2PLANE_PACK10:
	case MT_PIXEL_FORMAT_YVU420_2PLANE_PACK10:
		bpp = 16;
	default:
		break;
	}

	return bpp;
}

