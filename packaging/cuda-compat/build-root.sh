#!/usr/bin/env bash
# build-root.sh — assemble the CUDA-compatibility toolkit root.
#
# Produces a self-contained tree that mirrors the installed layout:
#   <root>/bin/nvcc, nvlink, fatbinary, cuda-config
#   <root>/include/*.h            CUDA-named headers, generated + wrappers
#   <root>/lib64/libcudart.so.*   jump shim onto libmusart 1.5.4
#   <root>/lib64/libcuda.so.*     jump shim onto libmusa 1.5.4
#   <root>/nvvm/libdevice/        libdevice bitcode link for toolkit discovery
#
# Usage: build-root.sh <output-dir>
#
# SPDX-License-Identifier: MIT
set -euo pipefail

HERE="$(cd -- "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
OUT="${1:-}"
[[ -n "$OUT" ]] || { echo "usage: $0 <output-dir>" >&2; exit 2; }

MUSA_RT="${MUSA_RT:-/usr/local/musa}"
MUSA_SDK="${MUSA_SDK:-/usr/local/musa-5.2}"
[[ -d "$MUSA_RT/lib" ]] || { echo "missing $MUSA_RT/lib" >&2; exit 1; }
[[ -d "$MUSA_SDK/mtgpu/bitcode" ]] || { echo "missing $MUSA_SDK/mtgpu/bitcode" >&2; exit 1; }

rm -rf "$OUT"
mkdir -p "$OUT"/{bin,include,lib64,nvvm/libdevice}

install -m 0755 "$HERE/bin/nvcc" "$OUT/bin/nvcc"
install -m 0755 "$HERE/bin/cuda-config" "$OUT/bin/cuda-config"
install -m 0755 "$HERE/bin/nvlink" "$OUT/bin/nvlink"
install -m 0755 "$HERE/bin/fatbinary" "$OUT/bin/fatbinary"
install -m 0755 "$HERE/bin/musify-text" "$OUT/bin/musify-text"
mkdir -p "$OUT/cmake"
install -m 0644 "$HERE"/cmake/*.cmake "$OUT/cmake/"
install -m 0644 "$HERE"/include/*.h "$OUT/include/"

# Jump shims: cudaX -> musaX, cuX -> muX. ABI-identical tail calls generated
# from the runtime library's own export list, so the CUDA entry points are the
# MUSA entry points rather than a reimplementation.
cc_flags=(-O2 -fPIC)
build_shim() {
    local src="$1" soname="$2" link="$3"
    "${CC:-gcc}" "${cc_flags[@]}" -shared -o "$OUT/lib64/$soname" "$src" \
        -L"$MUSA_RT/lib" $link -Wl,-soname,"$soname" -Wl,--no-undefined
}
build_shim "$HERE/src/cudart_jumps.S" "libcudart.so.11.0" "-lmusart"
build_shim "$HERE/src/cuda_jumps.S"   "libcuda.so.1"     "-lmusa"
ln -sf libcudart.so.11.0 "$OUT/lib64/libcudart.so.11"
ln -sf libcudart.so.11.0 "$OUT/lib64/libcudart.so"
ln -sf libcuda.so.1 "$OUT/lib64/libcuda.so"

# CMake's CUDA support always links the device runtime alongside the runtime
# library. MUSA bundles device code in mcc, so cudadevrt has no library of its
# own; an empty stub satisfies the link name. The static runtime variants map
# onto the MUSA static archives the SDK ships.
printf '/* device runtime placeholder: MUSA bundles device code in mcc */\n' >"$OUT/lib64/cudadevrt.c"
"${CC:-gcc}" -O2 -fPIC -shared -o "$OUT/lib64/libcudadevrt.so" "$OUT/lib64/cudadevrt.c" \
    -Wl,-soname,libcudadevrt.so
ln -sf "$MUSA_RT/lib/libmusart_static.a" "$OUT/lib64/libcudart_static.a"
ln -sf "$MUSA_RT/lib/libmusa_static.a"  "$OUT/lib64/libcuda_static.a"

# Toolkit discovery (CMake) requires <root>/nvvm/libdevice to exist; point it
# at the MUSA device bitcode the compiler actually uses.
ln -sf "$MUSA_SDK/mtgpu/bitcode/libdevice.bc" "$OUT/nvvm/libdevice/libdevice.10.bc"

cat >"$OUT/include/cuda_compat_version.h" <<EOF
/* Generated by build-root.sh — reports the compat layer build. */
#ifndef MUSA_CUDA_COMPAT_VERSION_H
#define MUSA_CUDA_COMPAT_VERSION_H
#define MUSA_CUDA_COMPAT_VERSION "1.0.0"
#endif
EOF

echo "built $OUT"
